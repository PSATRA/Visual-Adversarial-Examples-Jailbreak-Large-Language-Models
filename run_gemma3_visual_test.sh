# —— Configuration —— 
# Replace the following paths with your actual locations:

# Path to the CSV file containing Goal/Target pairs
INSTRUCT_PAIRS="/gpfs-flash/hulab/zhangwei_srt/lige/princeton/harmful_corpus/JBB-harmful-behaviors.csv"

# Path to the adversarial image (adv_best_noise.png) generated by APGD
ADV_IMG_PATH="/gpfs-flash/hulab/zhangwei_srt/lige/princeton/gemma3-4b-unconstrained/adv_iter_2000.png"

# Path to the Gemma3 checkpoint directory
MODEL_CKPT="/gpfs-flash/hulab/zhangwei_srt/lige/weights/gemma-3-4b-it"

# Device to run on (e.g., cuda:0, cuda:7, or cpu)
DEVICE="cuda:7"

# Random seed (optional; default in script is 17)
