#!/usr/bin/env bash
# ------------------------------------------------------------
# run_gemma3_visual_test.sh
#
# This script calls gemma3_visual_test.py and passes the necessary command-line arguments.
# Usage:
#   bash run_gemma3_visual_test.sh
